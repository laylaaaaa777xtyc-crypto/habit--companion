function getReply(roleId, userMessage, userData) {
  const char = responses[roleId];
  if (!char) return '你好！请先选择一个AI伙伴哦～';

  const msg = userMessage;
  let scenario = 'ask_progress';

  if (/谢|感谢|谢谢|thanks/i.test(msg)) scenario = 'saying_thanks';
  else if (/再见|晚安|拜拜|bye|goodbye|睡了|休息了/i.test(msg)) scenario = 'saying_goodbye';
  else if (/难|困难|做不到|放弃|坚持不|太累|好难/i.test(msg)) scenario = 'sharing_difficulty';
  else if (/怎么办|建议|方法|技巧|如何|怎么做|诀窍/i.test(msg)) scenario = 'asking_advice';
  else if (/加油|鼓励|坚持|打气|激励/i.test(msg)) scenario = 'request_encouragement';
  else if (/进度|怎么样|情况|成绩|数据|多少|等级/i.test(msg)) scenario = 'ask_progress';
  else if (userData && userData.streak_days >= 30) scenario = 'streak_milestone_30';
  else if (userData && userData.streak_days >= 7) scenario = 'streak_milestone_7';
  else if (userData && userData.streak_days >= 3) scenario = 'streak_milestone_3';

  const pool = char.scenarios[scenario] || char.scenarios['ask_progress'];
  let reply = pool[Math.floor(Math.random() * pool.length)];

  if (userData) {
    reply = reply
      .replace(/\{streak\}/g, userData.streak_days || 0)
      .replace(/\{level\}/g, userData.level || 1)
      .replace(/\{xp\}/g, userData.total_xp || 0);
  }

  return reply;
}

module.exports = { responses, CHARACTER_META, getReply };
